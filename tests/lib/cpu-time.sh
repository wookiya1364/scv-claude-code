#!/usr/bin/env bash
# cpu-time.sh — 속도 시험이 벽시계 대신 "그 일에 쓴 CPU 시간"을 재는 데 쓰는 함수 (0.89.2+).
#
# 왜 있나: 다른 일로 붐비는 공용 검사 기계에서는 벽시계 시간이 크게 늘지만(2026-11-11 맥 CI: 같은 코드가 1.5~2배),
# 그 명령과 자식 프로세스가 쓴 CPU 시간은 훨씬 덜 흔들린다. 진짜 느려짐(더 많은 일을 함)은 CPU 시간에 그대로 나타난다.
# 맥 기본 bash 3.2 · 리눅스 bash 공통: 셸 내장 `times` 의 둘째 줄(자식들의 사용자 · 시스템 시간)을 읽는다.

# cpu_mark <변수 이름> — 이 셸이 지금까지 기다린 자식 프로세스들(그 자손 포함)이 쓴 CPU 초(사용자 + 시스템, 소수 셋째 자리)를
# 그 변수에 넣는다. 값을 출력으로 돌려주지 않는 이유: `$(…)` 로 부르면 하위 셸이 생기고, 하위 셸의 `times` 는 0 에서
# 시작한다 — 그래서 `times` 는 지금 셸에서 부르고 결과만 파일로 받아 읽는다. 앞뒤로 두 번 불러 차이를 쓴다.
cpu_mark() {
  local _cm_f _cm_v
  _cm_f="$(mktemp "${TMPDIR:-/tmp}/scv-cpu.XXXXXX" 2>/dev/null)" || { printf -v "$1" '%s' '0.000'; return 0; }
  times > "$_cm_f" 2>/dev/null
  _cm_v="$(awk 'NR == 2 { t = 0
                 for (i = 1; i <= 2; i++) { v = $i; gsub(/,/, ".", v); sub(/s$/, "", v); n = split(v, a, "m"); t += (n == 2) ? a[1] * 60 + a[2] : v + 0 }
                 printf "%.3f", t }' "$_cm_f" 2>/dev/null)"
  rm -f "$_cm_f"
  printf -v "$1" '%s' "${_cm_v:-0.000}"
}
