#!/usr/bin/env bash
# force-help.sh — 매 턴 SCV 를 준비시키는 preflight 의 문자열부.
#
# 이름의 유래는 "강제" 지만, 강제하는 것은 더 이상 없다. 0.39.0 은 응답 종료 시점에
# 모델을 되돌려 세워 help 호출을 강제했고, 그것이 비쌌다 — 되돌림은 모델이 답을 다
# 쓴 뒤에 걸리므로 되돌릴 때마다 답이 통째로 다시 생성됐다. 되돌림 한 번의 값은
# 모델 턴 하나이고, 그것은 진단 3KB 를 주입하는 값보다 훨씬 크다.
#
# 목적을 잘못 잡은 것이 근본 원인이었다. 목적은 "스킬이 호출되는 것" 이 아니라
# "이 턴에 SCV 의 현재 상태가 들어와 있는 것" 이었다. 호출은 수단이었을 뿐인데
# 그 수단을 강제하느라 목적보다 비싼 값을 치렀다. 그래서 지점을 턴의 시작으로
# 옮겼다: 프롬프트 훅이 진단을 직접 주입하면 목적이 곧바로 달성되고, 강제할 것이
# 남지 않는다.
#
# 여기 있는 것: 스위치 해석, 진단 잘라내기, 표시줄, 분류 지침.
# 여기 없는 것: 파일 읽기·쓰기·표준출력·명령 실행. 전부 훅이 한다.

# @pure
# 스위치 해석 — off 만 끈다. 값이 없거나 다른 값이면 켜져 있다. 기존 두 스위치
# (쉬운말·항상 라우팅)와 같은 규칙이라야 사용자가 규칙을 하나만 기억한다.
scv_force_switch() {
  local v="${1:-}"
  v="${v//[[:space:]]/}"
  v="${v//\"/}"
  v="${v//\'/}"
  # 대소문자는 case 로 본다. ${v,,} 는 bash 4 부터라 오래된 셸에서 조용히 깨진다.
  case "$v" in
    [Oo][Ff][Ff]) printf 'off' ;;
    *)            printf 'on'  ;;
  esac
}

# @pure
# 상태 점검 출력에서 진단부터 끝까지만 남긴다.
#
# 앞부분은 SCV 개요와 명령 목록이고 매 턴 글자 하나 다르지 않다 (실측 2,823바이트).
# 그것을 매 턴 실어 보내는 것은 같은 문장을 반복해서 사는 것과 같다. 뒤쪽 진단
# (실측 3,148바이트)만 이 턴에 대해 새로운 정보다.
#
# 표지를 못 찾으면 자르지 않고 전체를 돌려준다 — 점검 출력 형식이 바뀌었을 때
# 반쪽을 싣느니 많이 싣는 편이 낫다. 입력은 표준입력으로 받는다.
scv_force_trim_diagnosis() {
  # 전부 초기화한다 — 훅은 set -u 아래에서 돌고, 빈 채로 참조하면 그 자리에서 죽는다.
  local all="" line="" out="" seen=0
  while IFS= read -r line; do
    all="${all}${line}"$'\n'
    if [[ "$seen" == "0" && "$line" == *"Current project diagnosis"* ]]; then
      seen=1
    fi
    [[ "$seen" == "1" ]] && out="${out}${line}"$'\n'
  done
  if [[ "$seen" == "1" ]]; then printf '%s' "$out"; else printf '%s' "$all"; fi
}

# @pure
# 화면 표시줄 — 강제가 아니라 준비가 켜져 있다는 사실을 한 줄로.
# 인자: on|off. 사용자가 "되는지 안 되는지 구분이 안 간다" 고 한 것이 이 줄이 있는 이유이고,
# 되돌림을 걷어낸 뒤에도 그 요구는 그대로 남아 있으므로 이 줄도 남는다.
scv_force_banner() {
  [[ "${1:-off}" == "on" ]] || return 0
  printf '[SCV preflight] 이번 턴의 프로젝트 상태를 함께 실었다.'
}

# @pure
# 매 턴 맨 앞에 실리는 지시 블록.
#
# 0.40.0 은 이 지시를 진단 뒤에 두고 조건문으로 썼고, 무시됐다. 원인이 넷이었다.
#
#   1. 자기모순 — "다시 확인하지 말고 그대로 쓰라" 가 진단 재조회만 막으려던 말인데
#      액션 호출 전반을 막는 것처럼 읽혔다. 그 읽기가 더 단순해서 이겼다.
#   2. 위치 — 40줄짜리 진단 뒤에 묻혔다.
#   3. 형태 — 조건문이라 분류를 통과해야 행동에 닿았다.
#   4. 중복 — 같은 요구를 하는 블록이 둘이라 서로를 약화시켰다.
#
# 그래서 이 블록은 하나로 합쳐 맨 앞에 오고, 세 갈래를 명령으로 제시하고, 재조회
# 금지를 진단으로만 좁히고, 그 구멍을 닫는 문장을 덧붙인다.
#
# 그리고 볼륨 대신 **이유**를 준다. "부르라" 는 명령이고 명령은 무시될 수 있지만,
# "부르지 않으면 이 논의가 사라진다" 는 사실이다. 대화 모드는 주입이 대신할 수 없는
# 일을 한다 — 논의를 파일로 적어 세션이 끝나도 남긴다.
scv_force_routing() {
  printf '%s\n' "════════ SCV: 이 턴의 첫 행동 ════════"
  printf '%s\n' "아래 셋 중 하나를 고르고, 고른 것을 지금 실행하라. 답을 쓰기 전에."
  printf '%s\n' ""
  printf '%s\n' "  A. 이 메시지가 **앞으로 할 일**에 관한 것이면 — 만들자·고치자·바꾸자·"
  printf '%s\n' "     추가하자·이렇게 하고 싶다·이게 문제다 —"
  printf '%s\n' "     → SCV help 액션을 **이 메시지 전문을 인자로** 하여 지금 호출하라."
  printf '%s\n' "       다른 도구보다 먼저. 조사·파일 읽기·코드 수정보다 먼저."
  printf '%s\n' ""
  printf '%s\n' "  B. **지난 일을 찾는** 것이면 — 찾아줘·보여줘·지난·어떻게 했었지 —"
  printf '%s\n' "     → SCV help 액션을 같은 방식으로 지금 호출하라."
  printf '%s\n' ""
  printf '%s\n' "  C. 둘 다 아니면 — 인사·감사·짧은 확인·이미 SCV 액션이 실린 턴 —"
  printf '%s\n' "     → 아무 것도 부르지 말고 바로 답하라. 그것도 정당한 결과다."
  printf '%s\n' ""
  printf '%s\n' "A 를 골라야 하는데 그냥 답하는 것이 이 규칙의 유일한 실패다."
  printf '%s\n' "그렇게 하면 **이 논의는 어디에도 남지 않는다.** 대화 모드는 오간 말을 파일로"
  printf '%s\n' "적어 세션이 끝나도 살아남게 하고, 그 파일이 나중에 계획서의 근거가 된다."
  printf '%s\n' "아래 진단은 그 일을 대신하지 못한다 — 진단은 상태일 뿐 논의가 아니다."
  printf '%s\n' ""
  printf '%s\n' "아래 진단은 이번 턴의 프로젝트 상태다. **상태를 다시 조회하지 않는 데에만**"
  printf '%s\n' "쓰라. A 나 B 를 골랐다면 진단이 이미 있어도 호출은 그대로 해야 한다 —"
  printf '%s' "진단을 받은 것은 호출을 건너뛸 이유가 되지 않는다. 끄는 법: scv/scv_settings.json SCV_ALWAYS_ON=off."
}
