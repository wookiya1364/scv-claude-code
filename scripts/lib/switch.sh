#!/usr/bin/env bash
# lib/switch.sh — SCV 스위치 값 해석 하나. 여러 기능이 같은 규칙을 쓴다.
#
# 예전에는 기능마다(드림 · 항상 라우팅 · help 상태 · 재개 요약 · 실체 보여 주기) 같은 함수를
# 따로 두었다 — 두 훅이 서로의 lib 에 묶이지 않게. 이 파일은 어느 기능의 것도 아니라서,
# 각 lib 이 이것만 불러오면 훅끼리는 여전히 서로를 모른다(2026-11-01, 순수함수 사전 계획).

# @pure
# 역할: 설정 값을 on|off 로 정한다 — off 만 끄고(대소문자 · 공백 · 따옴표 무관) 비었거나 다른 값은 on
# 종류: 판정
# 예: ' "OFF" ' → "off"
# 예: "" → "on"
# 예: maybe → "on"
# 대소문자는 case 로 본다. ${v,,} 는 bash 4 부터라 맥 기본 bash 3.2 로 훅이 돌면 깨진다.
scv_switch() {
  local v="${1:-}"
  v="${v//[[:space:]]/}"; v="${v//\"/}"; v="${v//\'/}"
  case "$v" in
    [Oo][Ff][Ff]) printf 'off' ;;
    *)            printf 'on'  ;;
  esac
}
